"""Cluster foundation models from an existing per-WSI Linear CKA result.

This standalone plotting utility extracts the dendrogram analysis from
``pca_foundation_embeddings.py``. It averages coordinate-aligned Linear CKA
over WSIs, converts similarity to ``1 - CKA`` distance, and applies average
linkage hierarchical clustering. No feature embedding is reloaded and no CKA
value is recomputed.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.cluster.hierarchy import dendrogram, fcluster, linkage
from scipy.spatial.distance import squareform


plt.rcParams["pdf.fonttype"] = 42
plt.rcParams["ps.fonttype"] = 42
plt.rcParams["svg.fonttype"] = "none"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot an average-linkage foundation-model dendrogram from pairwise Linear CKA."
    )
    parser.add_argument(
        "--cka-file",
        type=Path,
        required=True,
        help="pairwise_cka_by_wsi.csv generated by compute_linear_cka.py.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        required=True,
        help="Directory for the dendrogram and accompanying summary CSV files.",
    )
    parser.add_argument("--output-name", default="foundation_model_dendrogram")
    parser.add_argument(
        "--n-clusters",
        type=int,
        default=0,
        help="Optional number of flat clusters for branch colours and cluster assignments; 0 uses SciPy's default colouring.",
    )
    parser.add_argument(
        "--title",
        default="Foundation Model Clustering from 1 - Linear CKA",
    )
    args = parser.parse_args()
    if not args.output_name.strip():
        parser.error("--output-name must not be empty.")
    if args.n_clusters == 1 or args.n_clusters < 0:
        parser.error("--n-clusters must be 0 or at least 2.")
    return args


def canonical_pair(left: object, right: object) -> tuple[str, str]:
    return tuple(sorted((str(left), str(right))))


def build_mean_cka_matrix(path: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    if not path.is_file():
        raise FileNotFoundError(f"CKA file not found: {path}")
    frame = pd.read_csv(path)
    required = {"encoder_a", "encoder_b", "linear_cka"}
    missing = sorted(required - set(frame.columns))
    if missing:
        raise ValueError(f"{path}: missing required columns {missing}.")

    frame = frame.loc[:, ["encoder_a", "encoder_b", "linear_cka"]].copy()
    frame["encoder_a"] = frame["encoder_a"].astype(str)
    frame["encoder_b"] = frame["encoder_b"].astype(str)
    frame["linear_cka"] = pd.to_numeric(frame["linear_cka"], errors="coerce")
    frame = frame.dropna(subset=["linear_cka"])
    frame = frame[frame["encoder_a"] != frame["encoder_b"]]
    if frame.empty:
        raise ValueError(f"{path}: no valid between-encoder Linear CKA rows were found.")
    if (frame["linear_cka"] < -1e-6).any() or (frame["linear_cka"] > 1.0 + 1e-6).any():
        raise ValueError(f"{path}: Linear CKA values must lie in [0, 1].")

    pairs = [canonical_pair(left, right) for left, right in zip(frame.encoder_a, frame.encoder_b)]
    frame["encoder_a"] = [pair[0] for pair in pairs]
    frame["encoder_b"] = [pair[1] for pair in pairs]
    pair_summary = (
        frame.groupby(["encoder_a", "encoder_b"], as_index=False)["linear_cka"]
        .agg(["mean", "std", "count"])
        .reset_index()
        .rename(columns={"mean": "mean_linear_cka", "std": "std_linear_cka", "count": "n_wsi"})
    )
    names = sorted(set(pair_summary["encoder_a"]).union(pair_summary["encoder_b"]))
    if len(names) < 2:
        raise ValueError(f"{path}: at least two encoders are required.")
    matrix = pd.DataFrame(np.eye(len(names), dtype=np.float64), index=names, columns=names)
    for row in pair_summary.itertuples(index=False):
        matrix.loc[row.encoder_a, row.encoder_b] = row.mean_linear_cka
        matrix.loc[row.encoder_b, row.encoder_a] = row.mean_linear_cka
    if matrix.isna().to_numpy().any():
        missing_pairs = [
            f"{left} || {right}"
            for left_index, left in enumerate(names)
            for right in names[left_index + 1 :]
            if pd.isna(matrix.loc[left, right])
        ]
        raise ValueError(f"{path}: missing CKA values for pair(s): {missing_pairs}")
    return matrix, pair_summary


def threshold_for_cluster_count(linkage_matrix: np.ndarray, n_clusters: int) -> float:
    n_samples = linkage_matrix.shape[0] + 1
    if not 2 <= n_clusters <= n_samples:
        raise ValueError(f"--n-clusters must be between 2 and {n_samples} for this CKA matrix.")
    heights = linkage_matrix[:, 2]
    if n_clusters == n_samples:
        return max(0.0, float(heights[0]) - 1e-12)
    lower = float(heights[n_samples - n_clusters - 1])
    upper = float(heights[n_samples - n_clusters])
    return (lower + upper) / 2.0


def plot_dendrogram(
    linkage_matrix: np.ndarray,
    names: list[str],
    title: str,
    color_threshold: float | None,
    output_path: Path,
) -> list[str]:
    fig, ax = plt.subplots(
        figsize=(max(10.0, len(names) * 0.82), 6.5),
        constrained_layout=True,
    )
    result = dendrogram(
        linkage_matrix,
        labels=names,
        leaf_rotation=50,
        leaf_font_size=9,
        color_threshold=color_threshold,
        ax=ax,
    )
    ax.set_title(title)
    ax.set_ylabel("Average-linkage distance (1 - Linear CKA)")
    ax.grid(axis="y", alpha=0.25)
    fig.savefig(output_path, dpi=600, bbox_inches="tight")
    fig.savefig(output_path.with_suffix(".pdf"), format="pdf", bbox_inches="tight")
    fig.savefig(output_path.with_suffix(".svg"), format="svg", bbox_inches="tight")
    plt.close(fig)
    return [str(name) for name in result["ivl"]]


def main() -> None:
    args = parse_args()
    similarity, pair_summary = build_mean_cka_matrix(args.cka_file)
    names = list(similarity.index)
    distance = np.clip(1.0 - similarity.to_numpy(dtype=np.float64), 0.0, 1.0)
    np.fill_diagonal(distance, 0.0)
    linkage_matrix = linkage(squareform(distance, checks=False), method="average")

    color_threshold = None
    cluster_assignments = None
    if args.n_clusters:
        color_threshold = threshold_for_cluster_count(linkage_matrix, args.n_clusters)
        cluster_assignments = fcluster(linkage_matrix, t=args.n_clusters, criterion="maxclust")

    args.output_dir.mkdir(parents=True, exist_ok=True)
    output_path = args.output_dir / f"{args.output_name}.png"
    leaf_order = plot_dendrogram(
        linkage_matrix,
        names,
        args.title,
        color_threshold,
        output_path,
    )
    similarity.to_csv(
        args.output_dir / "mean_linear_cka_similarity.csv",
        encoding="utf-8-sig",
        float_format="%.6f",
    )
    pd.DataFrame(distance, index=names, columns=names).to_csv(
        args.output_dir / "linear_cka_distance.csv",
        encoding="utf-8-sig",
        float_format="%.6f",
    )
    pair_summary.to_csv(
        args.output_dir / "linear_cka_pair_summary.csv",
        index=False,
        encoding="utf-8-sig",
        float_format="%.6f",
    )
    if cluster_assignments is not None:
        pd.DataFrame({"encoder": names, "cluster": cluster_assignments}).sort_values(
            ["cluster", "encoder"]
        ).to_csv(
            args.output_dir / "foundation_model_cluster_assignments.csv",
            index=False,
            encoding="utf-8-sig",
        )
    metadata = {
        "cka_file": str(args.cka_file),
        "estimator": "mean_per_wsi_centered_linear_cka",
        "distance": "1 - mean_linear_cka",
        "linkage": "average",
        "encoder_names": names,
        "dendrogram_leaf_order": leaf_order,
        "n_clusters": int(args.n_clusters) if args.n_clusters else None,
        "color_threshold": color_threshold,
        "outputs": {
            "png": str(output_path),
            "pdf": str(output_path.with_suffix(".pdf")),
            "svg": str(output_path.with_suffix(".svg")),
        },
    }
    (args.output_dir / f"{args.output_name}_metadata.json").write_text(
        json.dumps(metadata, indent=2), encoding="utf-8"
    )
    print(f"Saved dendrogram: {output_path}")
    print(f"Leaf order: {', '.join(leaf_order)}")


if __name__ == "__main__":
    main()
